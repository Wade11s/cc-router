// 小票主题 webfont 生成脚本 (字体变更时运行):
//   node scripts/collect-receipt-fonts.mjs
//
// 生成两个提交进仓库的文件:
//   1. src/receipt-fonts.css        — @font-face 指向公共 CDN 的双源 URL
//   2. THIRD-PARTY-NOTICES.md       — 字体归属声明 + OFL-1.1 全文
//
// 把 @fontsource 各字重 css 的 @font-face 改写成指向公共 CDN 的双源 URL,
// 合并生成 src/receipt-fonts.css (提交进仓库):
//   1. cdn.jsdelivr.net (主源, 全球快, 国内时好时坏)
//   2. registry.npmmirror.com (兜底, 阿里云 npm 镜像, 国内稳; 路径是双 files/)
// 浏览器按 src 顺序逐个尝试, 主源失败自动落到兜底; 都失败时 font-display: swap
// 回退系统字体。字体不打包进安装包 (woff2 合计 ~2.2MB), 不占自有 OSS。
// CSP font-src 需放行上述两个域名 (tauri.conf.json)。
//
// 归属声明同源生成 (attribution / 许可证正文均直接读 node_modules), 避免手抄
// 版权声明 + 100 行许可证正文出错, 加减字体时自动同步。
//
// 声明同时覆盖界面字体: src/fonts.ts 里 import 的 @fontsource 包由 Vite 打进
// dist, 随安装包 (与网页界面) 分发, 构成 OFL 再分发。界面字体清单直接从
// src/fonts.ts 解析, 改界面字体后重跑本脚本即可, 不必在这里再登记一遍。

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_CSS = join(ROOT, "src", "receipt-fonts.css");
const OUT_NOTICES = join(ROOT, "THIRD-PARTY-NOTICES.md");
const UI_FONTS_SRC = join(ROOT, "src", "fonts.ts");

/** [package, weights(css 文件名 stem)] — 与 7 个小票主题实际使用的字重一一对应 */
const SPECS = [
  ["dotgothic16", ["400"]],
  ["courier-prime", ["400", "700"]],
  ["ibm-plex-mono", ["400", "500", "700"]],
  ["space-mono", ["400", "700"]],
  ["cormorant-garamond", ["600", "600-italic"]],
  ["archivo", ["400", "600", "800"]],
  ["caveat", ["500", "700"]],
  ["oswald", ["500", "700"]],
  ["archivo-narrow", ["400", "600"]],
];

/** metadata 的 attribution 会把同一句版权按 .ttf 逐文件重复一遍, 截断到主声明。
 *  主声明已含年份 + 权利人 + 上游 URL, 后续重复不增加任何信息。 */
function primaryAttribution(text) {
  const m = text.match(/\s+\S+\.ttf:/);
  return (m ? text.slice(0, m.index) : text).trim();
}

/** 取 @fontsource LICENSE 里分隔线之后的许可证正文 (顶部的 copyright 段各家不同)。 */
function licenseBody(pkgDir) {
  const raw = readFileSync(join(pkgDir, "LICENSE"), "utf8");
  const i = raw.search(/^-{10,}\s*$/m);
  if (i < 0) throw new Error(`${pkgDir}/LICENSE: 找不到许可证正文分隔线`);
  return raw.slice(i).trim();
}

/** src/fonts.ts 里 import 的 @fontsource 包名 (去重, 保持出现顺序)。 */
function uiFontPackages() {
  const src = readFileSync(UI_FONTS_SRC, "utf8");
  const pkgs = [...src.matchAll(/^\s*import\s+["']@fontsource\/([^/"']+)\//gm)].map((m) => m[1]);
  if (pkgs.length === 0) throw new Error(`${UI_FONTS_SRC}: 没有解析到任何 @fontsource import`);
  return [...new Set(pkgs)];
}

/** 读一个 @fontsource 包的归属信息 (家族名 / 许可证 / 版权声明 / 许可证正文)。 */
function fontInfo(pkg) {
  const pkgDir = join(ROOT, "node_modules", "@fontsource", pkg);
  const meta = JSON.parse(readFileSync(join(pkgDir, "metadata.json"), "utf8"));
  // 声明里写着「均未声明 RFN」, 且界面字体是子集化后沿用原名打包的 —— 有 RFN 就不能
  // 这么做。RFN 写在许可证正文分隔线之前的版权段里 ("with Reserved Font Name ...")。
  const raw = readFileSync(join(pkgDir, "LICENSE"), "utf8");
  const header = raw.slice(0, Math.max(0, raw.search(/^-{10,}\s*$/m)));
  if (/reserved font name/i.test(header) || /reserved font name/i.test(meta.license.attribution)) {
    throw new Error(`@fontsource/${pkg} 声明了 Reserved Font Name, 子集化后不能沿用原名分发, 需人工处理。`);
  }
  return {
    pkg,
    family: meta.family,
    license: meta.license.type,
    attribution: primaryAttribution(meta.license.attribution),
    body: licenseBody(pkgDir),
  };
}

const chunks = [
  `/* GENERATED by scripts/collect-receipt-fonts.mjs — do not edit by hand.
 * 小票主题 webfont: jsDelivr 主源 + npmmirror 兜底, 离线回退系统字体。
 * 重新生成: node scripts/collect-receipt-fonts.mjs */
`,
];
let faces = 0;
const fonts = [];

for (const [pkg, weights] of SPECS) {
  const pkgDir = join(ROOT, "node_modules", "@fontsource", pkg);
  const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
  fonts.push(fontInfo(pkg));
  for (const w of weights) {
    let css = readFileSync(join(pkgDir, `${w}.css`), "utf8");
    // 去掉 woff 兜底 (现代 webview 全支持 woff2)
    css = css.replace(/,\s*url\((?:\.\/)?files\/[^)]*\.woff\)\s*format\(['"]woff['"]\)/g, "");
    // ./files/x.woff2 → 双 CDN 源
    css = css.replace(
      /url\((?:\.\/)?files\/([^)]+\.woff2)\)\s*format\(['"]woff2['"]\)/g,
      (_m, file) => {
        faces += 1;
        return (
          `url(https://cdn.jsdelivr.net/npm/@fontsource/${pkg}@${version}/files/${file}) format('woff2'), ` +
          `url(https://registry.npmmirror.com/@fontsource/${pkg}/${version}/files/files/${file}) format('woff2')`
        );
      },
    );
    chunks.push(`/* ===== @fontsource/${pkg}@${version} ${w} ===== */\n${css}`);
  }
}

writeFileSync(OUT_CSS, chunks.join("\n"));
console.log(`wrote ${OUT_CSS} (${faces} @font-face, dual-CDN sources)`);

// ---- THIRD-PARTY-NOTICES.md ----
// 界面字体与小票字体合并成一张表 (同一款字体两处都用时只列一行)。
const receiptPkgs = new Set(fonts.map((f) => f.pkg));
const uiPkgs = new Set(uiFontPackages());
const allFonts = [...fonts, ...[...uiPkgs].filter((p) => !receiptPkgs.has(p)).map(fontInfo)];

// 模板假设所有字体共用同一份许可证正文, 只输出一份全文。加入其它许可证的字体时
// 这里硬失败而不是静默出一份错误的法律文件 —— 届时改成按许可证分组输出多份全文。
const licenses = new Set(allFonts.map((f) => f.license));
const bodies = new Set(allFonts.map((f) => f.body));
if (licenses.size !== 1 || bodies.size !== 1) {
  throw new Error(
    `字体许可证不统一 (${[...licenses].join(", ")}; ${bodies.size} 份不同正文)。\n` +
      `THIRD-PARTY-NOTICES.md 模板只输出一份许可证全文, 请改为按许可证分组后再运行。`,
  );
}
const [{ license: licenseId, body: licenseText }] = allFonts;
const usage = (pkg) =>
  [uiPkgs.has(pkg) && "界面 (随安装包分发)", receiptPkgs.has(pkg) && "小票 (CDN 按需加载)"]
    .filter(Boolean)
    .join("<br>");
const rows = [...allFonts]
  .sort((a, b) => a.family.localeCompare(b.family))
  .map((f) => `| ${f.family} | ${usage(f.pkg)} | ${f.attribution} |`)
  .join("\n");

writeFileSync(
  OUT_NOTICES,
  `# 第三方组件声明 (Third-Party Notices)

cc-router 本体以 MIT 许可证发布 (见 [LICENSE](LICENSE))。本文件声明项目使用的第三方
组件及其许可证。

> 字体部分由 \`scripts/collect-receipt-fonts.mjs\` 从 \`node_modules\` 生成, 请勿手工编辑。
> 许可证正文保留英文原文 —— 译本不具法律效力。

## 字体 (Fonts)

cc-router 使用以下 ${allFonts.length} 款字体, **全部为 SIL Open Font License 1.1 (${licenseId})**,
均取自 [Google Fonts](https://github.com/google/fonts) 经由 [Fontsource](https://fontsource.org) 分发。

| 字体 | 用途 | 版权声明 |
| --- | --- | --- |
${rows}

**分发方式**:

- **界面字体** (\`src/fonts.ts\`): 拉丁子集的 woff2 由 Vite 打进前端构建产物, 随安装包
  分发 (网页界面也从同一份产物提供), 离线可用。这构成 OFL 意义上的字体再分发, 其第 2
  条要求随附版权声明与许可证全文 —— 即本文件; 本文件同时经 \`tauri.conf.json\` 的
  \`bundle.resources\` 随安装包分发。
- **小票字体** (\`src/components/receipts/themes/\`): 字体文件既不在本仓库中, 也不随安装包
  分发 —— \`src/receipt-fonts.css\` 的 \`@font-face\` 仅引用公共 CDN (jsDelivr 主源 /
  npmmirror 兜底), 由 WebView 按需加载, 离线时回退系统字体; 导出的小票 HTML 同样只内嵌
  \`@font-face\` 规则而非字体数据。此处列出是为了向字体作者署名。

以上字体**均未声明 Reserved Font Name (RFN)** (生成脚本逐一检查), 因此衍生版本 (例如
界面字体所用的拉丁字符子集) 可继续使用原字体名。

OFL 同时明确豁免了用字体产出的文档 (见正文 PREAMBLE 末句): 用户从 cc-router 导出的
小票 HTML / PNG / PDF 不受 OFL 约束。

## 许可证全文 (${licenseId})

以下正文为上述 ${allFonts.length} 款字体共用, 逐字取自 \`node_modules/@fontsource/*/LICENSE\`。

\`\`\`
${licenseText}
\`\`\`

## 其他依赖

前端 npm 依赖见 [\`package.json\`](package.json) 与 \`pnpm-lock.yaml\`, Rust 依赖见
[\`src-tauri/Cargo.toml\`](src-tauri/Cargo.toml) 与 \`Cargo.lock\`; 各自许可证随包分发,
未在此逐一转录。
`,
);
console.log(`wrote ${OUT_NOTICES} (${allFonts.length} fonts, ${licenseId})`);
